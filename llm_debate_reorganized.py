    try:
        verdict = extract_json(judge_raw)
    except json.JSONDecodeError:
        verdict = {"verdict": "AI" if ai_prob > 0.5 else "Human", "confidence": 50, "reasoning": "Judge parse failure"}

    return {
        "transcript": state.transcript,
        "rounds_run": state.round_num + 1,
        "verdict": verdict,
        "judge_raw": judge_raw,
        "token_log": token_log,   # ← returned so you can inspect/plot after the run
    }

