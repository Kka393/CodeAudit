"""### Forensic feature extraction
Extracts the structural signals (empty-line ratio, entropy, identifier length, line-length variance) that get injected into every agent's prompt, mirroring the paper's Phase 1 stylometric extraction.
"""

import re, math
from collections import Counter
import json

def extract_forensic_report(code: str) -> dict:
    lines = code.splitlines()
    total = max(len(lines), 1)
    blank = sum(1 for l in lines if not l.strip())
    r_void = blank / total

    chars = Counter(code)
    n = len(code) or 1
    entropy = -sum((c/n) * math.log2(c/n) for c in chars.values())

    identifiers = re.findall(r'\b[a-zA-Z_]\w*\b', code)
    avg_id_len = sum(len(i) for i in identifiers) / max(len(identifiers), 1)
    line_lengths = [len(l) for l in lines]

    return {
        "empty_line_ratio": round(r_void, 4),
        "char_entropy": round(entropy, 3),
        "avg_identifier_length": round(avg_id_len, 2),
        "avg_line_length": round(sum(line_lengths)/total, 2),
        "line_length_std": round((sum((l-sum(line_lengths)/total)**2 for l in line_lengths)/total)**0.5, 2),
    }

