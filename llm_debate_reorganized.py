def call_llm(provider: str, prompt: str, temperature: float, max_tokens: int = 1500,
             max_retries: int = 2, timeout: float = 30.0) -> str:
    """Single OpenAI-compatible call wrapper shared by every agent role."""
    resp = None
    for attempt in range(max_retries + 1):
        try:
            resp = CLIENTS[provider].chat.completions.create(
                model=MODELS[provider],
                messages=[{"role": "user", "content": prompt}],
                temperature=temperature,
                max_tokens=max_tokens,
                timeout=timeout,
            )
            # Some providers (notably free OpenRouter models) return HTTP 200 with
            # an error embedded in the body instead of raising — choices comes back
            # None or []. Treat that the same as a failed call and retry.
            if not resp or not getattr(resp, "choices", None):
                error_info = getattr(resp, "error", None) if resp else "no response object"
                if attempt == max_retries:
                    print(f"❌ {provider}/{MODELS[provider]} returned no choices after {max_retries + 1} attempts. Raw error: {error_info}")
                    return ""
                wait = 5 * (attempt + 1)
                print(f"⚠️ {provider}/{MODELS[provider]} returned no choices (attempt {attempt + 1}/{max_retries + 1}). Error: {error_info}. Retrying in {wait}s...")
                time.sleep(wait)
                continue
            break
        except (APITimeoutError, APIConnectionError) as e:
            if attempt == max_retries:
                print(f"❌ {provider}/{MODELS[provider]} timed out after {max_retries + 1} attempts. Skipping this call.")
                return ""
            wait = 5 * (attempt + 1)
            print(f"⚠️ {provider}/{MODELS[provider]} timed out (attempt {attempt + 1}/{max_retries + 1}). Retrying in {wait}s...")
            time.sleep(wait)
        except APIStatusError as e:
            if "temperature" in str(e).lower():
                print(f"⚠️ {provider}/{MODELS[provider]} rejected temperature param, retrying without it.")
                resp = CLIENTS[provider].chat.completions.create(
                    model=MODELS[provider],
                    messages=[{"role": "user", "content": prompt}],
                    max_tokens=max_tokens,
                    timeout=timeout,
                )
                break
            raise

    if not resp or not getattr(resp, "choices", None):
        print(f"❌ {provider}/{MODELS[provider]} gave up with no valid response.")
        return ""

    message = resp.choices[0].message
    content = (message.content or "").strip()
    finish_reason = resp.choices[0].finish_reason

    if not content:
        reasoning = getattr(message, "reasoning", None) or getattr(message, "reasoning_content", None)
        if reasoning:
            print(f"⚠️ {provider}/{MODELS[provider]} returned empty content (finish_reason={finish_reason}); using reasoning field instead.")
            return reasoning.strip()
        print(f"⚠️ {provider}/{MODELS[provider]} returned a completely empty response (finish_reason={finish_reason}).")

    return content

