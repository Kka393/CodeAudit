from dataclasses import dataclass, field

@dataclass
class DebateState:
    code: str
    profile: dict
    ai_prob: float
    transcript: list = field(default_factory=list)  # [{"role": "advocate", "round": 0, "content": "...", "confidence": 92}, ...]
    round_num: int = 0

    def history_for(self, role: str) -> str:
        """Format the transcript so an agent can see what's been argued so far."""
        if not self.transcript:
            return "No prior arguments yet — this is the opening round."
        lines = []
        for entry in self.transcript:
            lines.append(f"[Round {entry['round']}] {entry['role'].upper()}: {entry['content']}")
        return "\n\n".join(lines)

