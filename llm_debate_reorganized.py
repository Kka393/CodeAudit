def run_debate(code: str, ai_prob: float) -> dict:
    """Runs a simple single-turn debate between one Advocate and one Skeptic, judged by a third LLM."""
    profile = extract_forensic_report(code)

    advocate_arg = call_llm("groq", ADVOCATE_PROMPT.format(
        code=code, profile=profile, ai_prob=ai_prob), temperature=0.7)

    skeptic_arg = call_llm("gemini", SKEPTIC_PROMPT.format(
        code=code, profile=profile, ai_prob=ai_prob), temperature=0.7)

    judge_raw = call_llm("openrouter", JUDGE_PROMPT.format(
        advocate_argument=advocate_arg, skeptic_argument=skeptic_arg,
        ai_prob=ai_prob, profile=profile), temperature=0.0)

    try:
        verdict = extract_json(judge_raw)
    except json.JSONDecodeError:
        print("⚠️ Judge JSON parse failed. Raw judge output was:\n", judge_raw)
        verdict = {"verdict": "AI" if ai_prob > 0.5 else "Human",
                   "confidence": 50, "reasoning": "Judge parse failure, defaulted to classifier"}

    return {
        "advocate_argument": advocate_arg,
        "skeptic_argument": skeptic_arg,
        "judge_raw": judge_raw,
        "verdict": verdict,
    }

