"""### Confidence extraction (fixed)
**Bug fix:** the original regex `r"[Cc]onfidence:?\s*(\d+)"` only matched "Confidence:" immediately followed by digits. Real model output looks like *"Confidence that the snippet was authored by an AI: 94%"* or *"Confidence Score: 85/100"* — neither matched, so every extraction silently fell back to 50, made every round look artificially converged, and cut debates short after round 0. Fixed to tolerate a phrase gap and both `%`/`/100` formats, with a last-resort fallback.
"""

def extract_confidence(text: str) -> int:
    if not text or not text.strip():
        print("⚠️ extract_confidence received empty text — this is an upstream call_llm issue, not a parsing issue.")
        return 50

    patterns = [
        r"[Cc]onfidence[^\n\d]{0,40}?(\d{1,3})\s*(?:%|/\s*100|percent|\bout of 100\b)",
        r"[Cc]onfidence[^\n\d]{0,40}?(\d{1,3})\b",
        r"(\d{1,3})\s*(?:%|/\s*100)\s*(?:confiden\w*)",
    ]
    for pattern in patterns:
        matches = re.findall(pattern, text)
        if matches:
            val = int(matches[-1])
            if 0 <= val <= 100:
                return val

    all_matches = re.findall(r"(\d{1,3})\s*(?:%|/\s*100)", text)
    for val in reversed(all_matches):
        v = int(val)
        if 0 <= v <= 100:
            return v

    # Show the END of the response, not the start — confidence is always stated last
    print("⚠️ Could not extract confidence, defaulting to 50.")
    print("--- Last 300 chars of raw text (this is where the number should be) ---")
    print(text[-300:])
    return 50

