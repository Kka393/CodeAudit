from json_repair import repair_json

def extract_json(raw: str) -> dict:
    """Extract and repair a JSON object from LLM output, tolerant of code fences,
    reasoning preambles, and common malformations (missing quotes, trailing commas, etc.)."""
    raw = re.sub(r"<think>.*?</think>", "", raw, flags=re.DOTALL)
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw.strip(), flags=re.MULTILINE)

    start = cleaned.find("{")
    if start == -1:
        raise json.JSONDecodeError("No JSON object found", cleaned, 0)
    candidate = cleaned[start:]

    result = repair_json(candidate, return_objects=True)
    if not isinstance(result, dict) or not result:
        raise json.JSONDecodeError("json_repair could not produce a valid object", candidate, 0)
    return result

