    state = DebateState(code=code, profile=profile, ai_prob=ai_prob)

    token_log = []  # ← collects (round, role, prompt_tokens) for inspection after the run

    for round_num in range(max_rounds):
        state.round_num = round_num

        if round_num == 0:
            adv_prompt = ADVOCATE_PROMPT.format(code=code, profile=profile, ai_prob=ai_prob)
            skep_prompt = SKEPTIC_PROMPT.format(code=code, profile=profile, ai_prob=ai_prob)
        else:
            adv_prompt = REBUTTAL_ADVOCATE_PROMPT.format(code=code, profile=profile, history=state.history_for("advocate"))
            skep_prompt = REBUTTAL_SKEPTIC_PROMPT.format(code=code, profile=profile, history=state.history_for("skeptic"))

        adv_tokens = count_tokens(adv_prompt)
        skep_tokens = count_tokens(skep_prompt)
        token_log.append({"round": round_num, "role": "advocate", "prompt_tokens": adv_tokens})
        token_log.append({"round": round_num, "role": "skeptic", "prompt_tokens": skep_tokens})
        print(f"[Round {round_num}] Advocate prompt: {adv_tokens} tokens | Skeptic prompt: {skep_tokens} tokens")

        adv_response = call_llm("groq", adv_prompt, temperature=0.7)
        skep_response = call_llm("gemini", skep_prompt, temperature=0.7)

        adv_conf = extract_confidence(adv_response)
        skep_conf = extract_confidence(skep_response)

        state.transcript.append({"role": "advocate", "round": round_num, "content": adv_response, "confidence": adv_conf})
        state.transcript.append({"role": "skeptic", "round": round_num, "content": skep_response, "confidence": skep_conf})

        gap = abs(adv_conf - (100 - skep_conf))
        print(f"Round {round_num}: Advocate {adv_conf}% AI | Skeptic {skep_conf}% Human | gap={gap}")

